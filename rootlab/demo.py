"""Export solver-generated examples for the static webpage comparison."""

import argparse
import json
from pathlib import Path

from .experiments import TARGET
from .workbench import CASES, solve_case

EXAMPLES = {
    "f3": ("Newton", "Secant", "Hybrid"),
    "f5-right": ("Bisection", "Newton", "Secant"),
    "f2": ("Bisection", "Fixed-point", "Newton", "Secant", "Hybrid"),
}


def samples():
    for case, methods in EXAMPLES.items():
        problem = CASES[case]
        for method in methods:
            example = dict(case=case, method=method)
            try:
                result = solve_case(case, method, tol_f=TARGET, tol_x=None)
            except ValueError as error:
                yield dict(example, status=str(error))
                continue
            yield dict(example, status=result.status, root=result.root,
                       residual=result.residual, error=abs(result.root - problem.reference),
                       updates=result.iterations,
                       inside=problem.interval[0] <= result.root <= problem.interval[1],
                       trace=[[s.kind, s.x, abs(s.fx)] for s in result.steps])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("assets/js/demo-data.js"))
    path = parser.parse_args().output
    data = json.dumps(list(samples()), indent=2, allow_nan=False)
    path.write_text("/* Generated by python -m rootlab.demo. */\n"
                    f"const ROOTLAB_EXAMPLES = {data};\n", encoding="utf-8")


if __name__ == "__main__":
    main()
